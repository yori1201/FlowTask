val TaskFlowShapes = Shapes(
    extraSmall = RoundedCornerShape(6.dp),
    small = RoundedCornerShape(10.dp),
    medium = RoundedCornerShape(16.dp),
    large = RoundedCornerShape(22.dp),
    extraLarge = RoundedCornerShape(28.dp)
)

@Composable
fun TaskFlowTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    fontScaleMultiplier: Float = 1.0f,
    content: @Composable () -> Unit
) {
    val colorScheme = if (darkTheme) TaskFlowDarkColors else TaskFlowLightColors
    val typography = remember(fontScaleMultiplier) { buildTaskFlowTypography(fontScaleMultiplier) }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = typography,
        shapes = TaskFlowShapes,
        content = content
    )
}
